class StrictKneeTests(unittest.TestCase):
    setUp = GateTests.setUp
    # Inherit the same fixture, not duplicate the gate tests.
    def start(self):
        self.source.enabled = True
        self.owner.auto_capture = False
        self.f.objects['virtual_sdcard'] = SimpleNamespace(file_path=lambda: str(self.path))
        self.f.objects['print_stats'].status.update(state='printing', info={'current_layer': 1})
        self.f.objects['gcode_move'].status['homing_origin'][2] = 0.
        self.f.objects['extruder'].status.update(pressure_advance=.05, smooth_time=.04)
        self.f.objects['bed_mesh'].status.update(mesh_matrix=[[0., 0.], [0., 0.]], probed_matrix=[[0., 0.], [0., 0.]])
        def motion(t):
            return dict(method='native_trapq_at_host_receipt', print_time=t,
                        live_position=[10,20,-2.6,0], live_velocity=40., live_extruder_velocity=1.)
        self.owner._motion_at = motion
        self.source.timeline[0]['conditions'] = self.source.conditions(self.owner._context_conditions())
        self.f.feed()
        self.owner.cmd_START(capture.Command(ADC=0, ACCEL=0))
        for _ in range(12): self.f.feed()
        self.assertTrue(self.source.last_gate['eligible'], self.source.last_gate['reasons'])
        scripts = []
        def move(line):
            scripts.append(line)
            self.f.objects['gcode_move'].status['homing_origin'][2] += float(line.split('Z_ADJUST=')[1].split()[0])
        self.f.gcode.run_script = move
        return scripts

    def test_explicit_margin_starts_only_after_known_steady_context(self):
        scripts = self.start()
        self.owner.cmd_KNEE(KneeCommand(MARGIN='.0075'))
        self.assertEqual(len(scripts), 1)
        self.assertIn('_ctx', self.owner.knee['key'])
        self.assertEqual(self.owner.knee['feature_fingerprint'], self.source.last_gate['fingerprint'])

    def test_missing_context_rejects_motion_but_keeps_recording(self):
        scripts = self.start(); self.source.state = 'error'; self.source.last_gate['eligible'] = False
        with self.assertRaisesRegex(ValueError, 'Slicer context not ready'):
            self.owner.cmd_KNEE(KneeCommand(MARGIN='.0075'))
        self.assertEqual(scripts, []); self.assertTrue(self.owner.active)

    def test_seed_uses_context_identity_and_legacy_margin_cannot_be_reused(self):
        scripts = self.start(); self.owner.knee_require_margin = True
        self.owner.cmd_KNEE_MARGIN(KneeCommand(MATERIAL='PLA',HEIGHT='.2',WIDTH='.45',SPEED='40',MARGIN='.0075'))
        self.owner.cmd_KNEE(KneeCommand())
        self.assertEqual(self.owner.knee['margin'], .0075)
        self.assertEqual(len(scripts), 1)

    def test_travel_blocks_lowering_without_discarding_prior_valid_samples(self):
        scripts = self.start(); self.owner.cmd_KNEE(KneeCommand(MARGIN='.0075'))
        self.owner.knee['readings'] = [123] * 10
        self.source.timeline.clear()
        self.f.feed()
        self.assertEqual(self.owner.knee['readings'], [123] * 10)
        self.assertEqual(len(scripts), 1)
        for _ in range(124): self.f.feed()
        self.assertIsNone(self.owner.knee)
        self.assertTrue(self.owner.active)
        self.assertEqual(len(scripts), 2)  # restores original, never steps lower

    def test_live_pressure_advance_change_aborts_and_restores(self):
        scripts = self.start(); self.owner.cmd_KNEE(KneeCommand(MARGIN='.0075'))
        self.f.objects['extruder'].status['pressure_advance'] = .08
        self.f.feed()
        self.assertIsNone(self.owner.knee); self.assertEqual(len(scripts), 2)



    def test_full_strict_search_fits_descending_knee_and_keeps_capture(self):
        scripts = self.start()
        self.owner.cmd_KNEE(KneeCommand(MARGIN='.0075', CONFIRM='0'))
        for _ in range(1800):
            z = self.f.objects['gcode_move'].status['homing_origin'][2]
            force = max(0., -.125 - z) * 2500.
            self.f.feed(raw=8000000 + round(force * 43.))
            if self.owner.knee is None: break
        self.assertIsNone(self.owner.knee)
        self.assertTrue(self.owner.active)
        self.assertAlmostEqual(self.owner.knee_last['knee'], -.125, delta=.002)
        self.assertAlmostEqual(self.f.objects['gcode_move'].status['homing_origin'][2], -.1175, delta=.002)

    def test_unscoped_legacy_seed_cannot_bypass_fingerprint_requirement(self):
        self.start(); self.owner.knee_require_margin = True
        self.owner._knee_save_margins({self.owner._knee_key(): {'margin': .125, 'n': 10}})
        with self.assertRaisesRegex(ValueError, 'Uncalibrated flow'):
            self.owner.cmd_KNEE(KneeCommand())
        self.assertIsNone(self.owner.knee)

    def test_context_mismatch_prevents_learning_after_user_adjustment(self):
        self.start()
        gate = self.source.last_gate
        self.owner.knee_last = dict(knee=-.125,target=-.1175,margin=.0075,key='test',fixed=False,
            user_adjusted=True,physics_sha256=gate['physics_sha256'],feature_fingerprint=gate['fingerprint'],live_conditions=gate['live'])
        self.f.objects['gcode_move'].status['homing_origin'][2] = -.1
        self.source.last_gate = dict(gate, live=dict(gate['live'], pressure_advance=.08))
        self.owner._knee_learn()
        self.assertEqual(self.owner._knee_margins(), {})



