SETTINGS = {'nozzle_diameter': '0.4', 'filament_diameter': '1.75',
            'filament_type': 'PLA', 'filament_flow_ratio': '1',
            'initial_layer_speed': '40', 'initial_layer_infill_speed': '40',
            'nozzle_temperature_initial_layer': '230', 'raft_layers': '0',
            'enable_mixed_color_sublayer':'0','spiral_mode':'0','flush_into_infill':'0',
            'flush_into_objects':'0','seam_slope_type':'none'}


def gcode(role='Internal solid infill', extra='', settings=None, e='2.5', header=''):
    values = dict(SETTINGS); values.update(settings or {})
    return ('; generated by OrcaSlicer 2.5.0-dev 606b50f1\n' + header +
            'G90\nM83\nG1 X0 Y0 Z0.2 F2400\n;LAYER_CHANGE\n;HEIGHT:0.2\n;WIDTH:0.5\n'
            ';TYPE:' + role + '\n' + extra + 'G1 X100 E' + e + ' F2400\n' +
            ';LAYER_CHANGE\nG1 Z0.4\n; CONFIG_BLOCK_START\n' +
            ''.join('; %s = %s\n' % kv for kv in values.items()) + '; CONFIG_BLOCK_END\n')


class ParserTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.path = Path(self.temp.name) / 'print.gcode'

    def parse(self, text):
        self.path.write_text(text)
        return parse_file(str(self.path))

    def test_footer_and_all_378_exported_bindings_retained_verbatim(self):
        registry = json.loads((Path(__file__).resolve().parents[1] /
            'reference/orca_606b50f1/parameter_registry_606b50f1.json').read_text())
        settings = {v['key']: 'disabled; 17%; "raw"' for v in registry['settings']}
        settings.update(SETTINGS)
        settings['enable_mixed_color_sublayer'] = '0'
        parsed = self.parse(gcode(settings=settings))
        self.assertTrue(parsed['eligible'], parsed['issues'])
        self.assertTrue(set(v['key'] for v in registry['settings']) <= set(parsed['settings']))
        self.assertEqual(parsed['settings']['layer_height'], 'disabled; 17%; "raw"')
        segment = next(iter(parsed['segments'].values()))
        self.assertTrue(segment['eligible'], segment['reasons'])
        self.assertEqual(segment['height'], .2)
        self.assertAlmostEqual(segment['e_per_mm'], .025)
        self.assertTrue(self.path.read_bytes()[segment['offset']:segment['end']].startswith(b'G1 X100'))

    def test_header_and_footer_config_supported_without_fabricated_defaults(self):
        text = gcode(); a = text.index('; CONFIG_BLOCK_START')
        parsed = self.parse(text[a:] + text[:a])
        self.assertTrue(parsed['eligible'])
        incomplete = self.parse(text.replace('; CONFIG_BLOCK_END', ''))
        self.assertFalse(incomplete['eligible'])
        self.assertIn('missing_complete_config_block', incomplete['issues'])

    def test_filename_and_notes_do_not_invalidate_physics(self):
        a = self.parse(gcode(settings={'notes': 'one', 'output_filename_format': 'a'}))
        b = self.parse(gcode(settings={'notes': 'two', 'output_filename_format': 'b'}))
        self.assertNotEqual(a['file_sha256'], b['file_sha256'])
        self.assertEqual(a['physics_sha256'], b['physics_sha256'])
        c = self.parse(gcode(settings={'filament_flow_ratio': '1.05'}))
        self.assertNotEqual(a['physics_sha256'], c['physics_sha256'])

    def test_unknown_setting_and_custom_scripts_are_part_of_physics(self):
        a = self.parse(gcode(settings={'future_setting': '1', 'machine_start_gcode': 'G28'}))
        b = self.parse(gcode(settings={'future_setting': '2', 'machine_start_gcode': 'G28'}))
        c = self.parse(gcode(settings={'future_setting': '1', 'machine_start_gcode': 'G28\\nM220 S90'}))
        self.assertNotEqual(a['physics_sha256'], b['physics_sha256'])
        self.assertNotEqual(a['physics_sha256'], c['physics_sha256'])

    def test_excluded_roles_missing_geometry_arcs_and_zhops_are_not_fit_data(self):
        for role in ('Support', 'Support interface', 'Skirt', 'Brim', 'Prime tower',
                     'Bridge', 'Ironing', 'Custom', 'future role'):
            with self.subTest(role=role):
                s = next(iter(self.parse(gcode(role=role))['segments'].values()))
                self.assertFalse(s['eligible'])
        for text in (gcode().replace(';WIDTH:0.5', ''), gcode().replace(';HEIGHT:0.2', ';HEIGHT:nan'),
                     gcode().replace('G1 X100', 'G2 X100'),
                     gcode().replace('G1 X100', 'G1 Z0.25 X100'),
                     gcode(e='-1'), gcode().replace('M83', 'G20\nM83')):
            s = next(iter(self.parse(text)['segments'].values()))
            self.assertFalse(s['eligible'], s)

    def test_nozzle_material_errors_and_multimaterial_mapping_fail_closed(self):
        for settings in ({'nozzle_diameter': 'nan'}, {'filament_flow_ratio': '-1'},
                         {'filament_type': 'PLA;PETG'}, {'filament_diameter': ''}, {'filament_type': ''}):
            self.assertFalse(self.parse(gcode(settings=settings))['eligible'])

    def test_conflicting_settings_and_oversized_line_rejected(self):
        p = self.parse(gcode().replace('; CONFIG_BLOCK_END', '; filament_flow_ratio = 1.2\n; CONFIG_BLOCK_END'))
        self.assertIn('conflicting_setting:filament_flow_ratio', p['issues'])
        with self.assertRaisesRegex(ValueError, 'line exceeds'):
            self.parse(';' + 'x' * 262145)

    def test_single_used_filament_header_resolves_array_index_without_start_parameters(self):
        p = self.parse(gcode(header='; filament: 2\n', settings={
            'filament_type':'PLA;PETG', 'filament_diameter':'1.75;1.75', 'filament_flow_ratio':'1;0.97'}))
        self.assertTrue(p['eligible'], p['issues'])
        self.assertEqual(next(iter(p['segments'].values()))['tool'], 1)
        self.assertEqual(p['used_filaments'], [1])

    def test_absolute_relative_e_and_reset_have_correct_extrusion(self):
        text = gcode().replace('M83', 'M82\nG92 E50').replace('G1 X100 E2.5', 'G1 X100 E52.5')
        self.assertAlmostEqual(next(iter(self.parse(text)['segments'].values()))['delta_e'], 2.5)


class GateTests(unittest.TestCase):
    def setUp(self):
        self.f = capture.CaptureTests(); self.f.setUp(); self.addCleanup(self.f.doCleanups)
        self.owner = self.f.cell; self.source = self.owner.slicer
        self.source.enabled = True
        self.path = Path(self.f.temp.name) / 'fixture.gcode'; self.path.write_text(gcode())
        self.source.snapshot = parse_file(str(self.path)); self.source.state = 'ready'; self.source.path = str(self.path)
        self.segment = next(iter(self.source.snapshot['segments'].values()))
        self.source.timeline.append(dict(segment=self.segment, start=0., end=1000., source_valid=True))
        self.context = dict(t=0., gcode=dict(speed_factor=1., extrude_factor=1.),
            heaters=dict(extruder=dict(temperature=230., target=230.), heater_bed=dict(temperature=60., target=60.)),
            extruder_state=dict(pressure_advance=.05, smooth_time=.04), fans={'fan': {'speed': 0.}},
            print_stats=dict(state='printing', info={'current_layer': 1}), mesh_identity='verified-mesh')
        self.source.timeline[0]['conditions'] = self.source.conditions(self.context)
        self.motion = dict(method='native_trapq_at_host_receipt', print_time=0., live_velocity=40., live_extruder_velocity=1.)

    def sample(self, t):
        self.context['t'] = t; self.motion['print_time'] = t
        return self.source.sample(t, self.motion, self.context)

    def ready(self):
        for n in range(26): result = self.sample(n / 10.)
        self.assertTrue(result['eligible'], result['reasons'])
        return result

    def test_queue_clock_identifies_executing_path_not_latest_read_path(self):
        good = self.ready()
        tower = dict(self.segment, role='prime tower', eligible=False, reasons=['unknown_or_excluded_role'])
        self.source.timeline[-1]['end'] = 20.
        self.source.timeline.append(dict(segment=tower, start=20., end=30., source_valid=True, conditions=self.source.conditions(self.context)))
        self.assertTrue(self.sample(3.)['eligible'])  # reader already queued the tower
        bad = self.sample(21.)
        self.assertFalse(bad['eligible']); self.assertEqual(bad['segment']['role'], 'prime tower')
        self.assertNotEqual(good['fingerprint'], bad['fingerprint'])

    def test_travel_and_fan_pa_flow_thermal_changes_reset_settling(self):
        self.ready(); self.motion['live_extruder_velocity'] = -1
        self.assertFalse(self.sample(3.)['eligible'])
        self.motion['live_extruder_velocity'] = 1
        self.assertIn('segment_settling', self.sample(3.1)['reasons'])
        for n in range(32, 75): self.sample(n / 10.)
        good = self.source.last_gate
        self.assertTrue(good['eligible'])
        self.context['extruder_state']['pressure_advance'] = .08
        changed = self.sample(7.5)
        self.assertFalse(changed['eligible']); self.assertNotEqual(good['fingerprint'], changed['fingerprint'])
        self.context['heaters']['heater_bed']['temperature'] = 58.
        self.assertIn('temperature_not_settled:heater_bed', self.sample(7.6)['reasons'])

    def test_rounding_does_not_change_steady_recipe_but_large_flow_change_does(self):
        original = self.ready()
        self.segment['e_per_mm'] = .025001
        self.assertEqual(original['fingerprint'], self.sample(2.6)['fingerprint'])
        self.segment['e_per_mm'] = .030
        changed = self.sample(2.7)
        self.assertNotEqual(original['fingerprint'], changed['fingerprint'])
        self.assertIn('extrusion_rate_transition', changed['reasons'])
        self.assertIn('extrusion_history_settling', changed['reasons'])

    def test_missing_or_ambiguous_timing_stale_context_and_fallback_are_excluded(self):
        self.ready(); self.source.timeline.append(dict(self.source.timeline[0]))
        self.assertIn('missing_or_ambiguous_queue_segment', self.sample(3.)['reasons'])
        self.source.timeline.pop(); self.motion['method'] = 'cached_status_fallback'
        self.assertIn('unverified_motion_clock', self.sample(3.1)['reasons'])
        self.motion['method'] = 'native_trapq_at_host_receipt'; self.context['t'] = 5
        self.assertIn('stale_live_context', self.source.sample(3.2, self.motion, self.context)['reasons'])

    def test_changed_file_invalidates_snapshot(self):
        self.ready(); self.f.objects['virtual_sdcard'] = SimpleNamespace(file_path=lambda: str(self.path))
        self.path.write_text(gcode(settings={'nozzle_diameter': '0.6'}))
        self.source.request()
